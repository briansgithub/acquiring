#!/usr/bin/env python3
"""Validate the maintained PWA audit and dependency graph; optionally render its ledger."""
import argparse
import json
import re
import subprocess
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
HERE = Path(__file__).resolve().parent
BASE = '801cf7984171d772afc4406ddb5c79c0cb7fd20a'

def git(*args, input=None):
    result = subprocess.run(['git', *args], cwd=ROOT, input=input,
                            text=True, encoding='utf-8', capture_output=True)
    if result.returncode:
        raise RuntimeError(result.stderr.strip())
    return result.stdout

def load(name):
    return json.loads((HERE / name).read_text(encoding='utf-8-sig'))

def objects(refs):
    if not refs:
        return {}
    rows = git('cat-file', '--batch-check', input='\n'.join(refs) + '\n').splitlines()
    return dict(zip(refs, [not row.endswith(' missing') for row in rows]))

def validate():
    parts = {part: load(f'history-{part}.json') for part in ('foundation','revision','aural')}
    rows = [row for group in parts.values() for row in group]
    expected = set(git('log','--full-history','--format=%H',BASE,'--','android','contracts').splitlines())
    actual = [row['sha'] for row in rows]
    assert len(actual) == len(set(actual)) == 262, 'Duplicate or missing inventory rows'
    assert set(actual) == expected, 'Ledger does not cover the frozen history'
    refs = set()
    for row in rows:
        assert row['reviewStatus'] == 'reviewed', f"Pending row: {row['sha']}"
        assert all(row.get(k) for k in ('kind','featureDelta','finalDisposition','evidence')), row['sha']
        for item in row['evidence']:
            match = re.match(r'^([0-9a-f]{8,40}(?:\^1)?):(.+)$', str(item))
            if match:
                refs.add(match.group(0))
    present = objects(sorted(refs))
    missing = [ref for ref, exists in present.items() if not exists]
    # A deleted file can be cited by its deleting diff; its parent must contain it.
    parents = {ref: ref.split(':',1)[0]+'^1:'+ref.split(':',1)[1] for ref in missing}
    parent_ok = objects(list(parents.values()))
    bad = [ref for ref in missing if not parent_ok[parents[ref]]]
    assert not bad, 'Invalid historical evidence references: '+repr(bad[:12])
    state = load('tasks.json')
    assert state['baseline'] == BASE
    tasks = state['tasks']
    by_id = {task['id']: task for task in tasks}
    assert len(tasks) == len(by_id) == 29
    assert set(by_id) == {f'T{i:02}' for i in range(29)}
    visiting, done = set(), set()
    def visit(key):
        assert key not in visiting, f'Dependency cycle at {key}'
        if key in done:
            return
        assert key in by_id, f'Unknown dependency {key}'
        visiting.add(key)
        task = by_id[key]
        assert task['acceptance'] and task['allowedPaths'] and task['nextAction']
        assert task['status'] in {'planned','in_progress','validating','complete','blocked'}
        for dep in task['dependsOn']:
            visit(dep)
            if task['status'] == 'complete':
                assert by_id[dep]['status'] == 'complete'
        visiting.remove(key)
        done.add(key)
    for key in by_id:
        visit(key)
    plan = (HERE/'IMPLEMENTATION_PLAN.md').read_text(encoding='utf-8-sig')
    table_ids = re.findall(r'^\| (T\d{2}) \|', plan, re.M)
    assert set(table_ids) == set(by_id), 'Plan/task table mismatch'
    for line in plan.splitlines():
        if not re.match(r'^\| T\d{2} \|', line):
            continue
        cells = [cell.strip() for cell in line.split('|')]
        task = by_id[cells[1]]
        deps = [] if cells[3] == '-' else cells[3].split(',')
        assert task['title'] == cells[2], f"Title drift: {task['id']}"
        assert task['dependsOn'] == deps, f"Dependency drift: {task['id']}"
        assert task['acceptance'] == cells[4], f"Acceptance drift: {task['id']}"
    if not state['implementationAuthorized']:
        assert all(t['status'] == 'planned' for t in tasks), 'Product tasks require authorization'
    else:
        assert state.get('authorizationEvidence'), 'Record the user authorization before implementation'
    for part, group in parts.items():
        print(f'{part}: {len(group)}/{len(group)} classified')
    print(f'PASS: 262 unique baseline commits; {len(refs)} resolvable evidence paths; 29 acyclic planned packages')
    return rows

def render(rows):
    def cell(value):
        return str(value).replace('|','\\|').replace('\n',' ')
    output = ['# Android commit feature ledger', '',
              f'Frozen Android authority: `{BASE}`. Generated by `python docs/pwa-port/validate_audit.py --render-history` from the three maintained JSON ledgers.', '',
              'This is a bounded critical-path source/diff/comment/test audit, not line-by-line review of every historical patch or fresh runtime verification. Dates are author dates; order is topological within each source period. Imports/merges and superseded behavior are explicitly retained to explain ancestry without duplicating implementation work.', '',
              '| Commit | Date | Kind | Actual delta | Final PWA disposition |',
              '| --- | --- | --- | --- | --- |']
    for row in rows:
        output.append('| '+ ' | '.join(cell(v) for v in
            (row['sha'][:8],row['date'],row['kind'],row['featureDelta'],row['finalDisposition'])) +' |')
    (HERE/'HISTORY.md').write_text('\n'.join(output)+'\n',encoding='utf-8')
    print('Rendered HISTORY.md')

if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--render-history',action='store_true')
    args = parser.parse_args()
    reviewed = validate()
    if args.render_history:
        render(reviewed)
