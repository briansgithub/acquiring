#!/usr/bin/env python3
"""Validate the post-801cf798 Android delta ledger and render ANDROID_DELTA.md.

Coverage rule: every non-merge android/contracts commit in forkPoint..nativeAuthority
must either have the same patch-id as a commit in the frozen 801cf798 history
(a rehashed copy that HISTORY.md already audits) or appear in commits[].
"""
import argparse
import json
import subprocess
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[1]
URL = 'https://github.com/briansgithub/acquiring'


def git(*args, input=None):
    return subprocess.run(['git', *args], cwd=ROOT, input=input, capture_output=True,
                          text=True, encoding='utf-8', check=True).stdout


def patch_ids(rev_args):
    shas = git('rev-list', '--no-merges', *rev_args, '--', 'android', 'contracts').split()
    out = {}
    for sha in shas:
        diff = git('show', sha, '--', 'android', 'contracts')
        line = git('patch-id', '--stable', input=diff).split()
        if line:
            out[sha] = line[0]
    return out


def validate(data):
    tasks = {t['id'] for t in json.loads((HERE / 'tasks.json').read_text(encoding='utf-8-sig'))['tasks']}
    ledger = {r['id'] for r in json.loads((HERE / 'feature-ledger.json').read_text(encoding='utf-8'))['rows']}
    new, prev, fork = data['nativeAuthority'], data['previousAuthority'], data['forkPoint']
    git('merge-base', '--is-ancestor', fork, new)
    audited = set(patch_ids([prev]).values())
    listed = {c['sha'] for c in data['commits']}
    rehashed, missing = 0, []
    for sha, pid in patch_ids([f'{fork}..{new}']).items():
        if sha in listed:
            continue
        if pid in audited:
            rehashed += 1
        else:
            missing.append(sha[:8])
    assert not missing, f'Unclassified Android commits: {missing}'
    feature_ids = {f['id'] for f in data['features']}
    assert len(feature_ids) == len(data['features'])
    assert not feature_ids & ledger, 'Delta feature IDs collide with feature-ledger.json'
    for c in data['commits']:
        git('merge-base', '--is-ancestor', c['sha'], new)
        assert c['kind'] and c['featureDelta'] and set(c['featureRows']) <= feature_ids, c['sha']
    for f in data['features']:
        assert f['pwaStatus'] in {'missing', 'partial', 'implemented'}, f['id']
        assert set(f['tasks']) <= tasks and set(f['reopens']) <= ledger, f['id']
        assert f['behavior'] and f['acceptance'] and f['pwa'], f['id']
        for path in f['native']:
            git('cat-file', '-e', f'{new}:{path}')
        assert any(f['id'] in c['featureRows'] for c in data['commits']), f'No commit evidence for {f["id"]}'
    print(f'PASS: {len(listed)} new commits, {rehashed} rehashed copies of audited commits, '
          f'{len(feature_ids)} delta features, pin {new[:8]}')


def render(data):
    cell = lambda v: str(v).replace('|', '\\|').replace('\n', ' ')
    new = data['nativeAuthority']
    lines = ['# Android delta after 801cf798', '',
             f'Current native authority: [`{new[:8]}`]({URL}/commit/{new}). The frozen history audit '
             f'([HISTORY.md](HISTORY.md), [FEATURE_LEDGER.md](FEATURE_LEDGER.md)) stays pinned to '
             f'`{data["previousAuthority"][:8]}`; this file adds only what changed after it. '
             'Generated by `python docs/pwa-port/validate_android_delta.py --render` from '
             '[android-delta-2026-11.json](android-delta-2026-11.json).', '',
             data['method'], '', '## Owner decisions', '']
    lines += [f'- {d}' for d in data['decisions']]
    lines += ['', '## Delta features', '', '| ID | Behavior | Packages | Reopens | PWA status |', '| --- | --- | --- | --- | --- |']
    for f in data['features']:
        lines.append(f"| {f['id']} | {cell(f['behavior'])} | {', '.join(f['tasks'])} | {', '.join(f['reopens']) or '-'} | {f['pwaStatus']} |")
    lines += ['', '## Acceptance', '']
    lines += [f"- **{f['id']}**: {f['acceptance']}" for f in data['features']]
    lines += ['', '## New commits', '', '| Commit | Date | Kind | Rows | Delta |', '| --- | --- | --- | --- | --- |']
    for c in data['commits']:
        lines.append(f"| [{c['sha'][:8]}]({URL}/commit/{c['sha']}) | {c['date']} | {c['kind']} | {', '.join(c['featureRows'])} | {cell(c['featureDelta'])} |")
    return '\n'.join(lines) + '\n'


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--render', action='store_true')
    args = parser.parse_args()
    data = json.loads((HERE / 'android-delta-2026-11.json').read_text(encoding='utf-8'))
    validate(data)
    target, output = HERE / 'ANDROID_DELTA.md', render(data)
    if args.render:
        target.write_text(output, encoding='utf-8')
    assert target.read_text(encoding='utf-8') == output, 'Run --render to update ANDROID_DELTA.md'
